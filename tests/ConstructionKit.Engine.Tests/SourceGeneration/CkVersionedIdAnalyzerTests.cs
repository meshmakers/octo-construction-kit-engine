using System.Collections.Immutable;
using Meshmakers.Octo.ConstructionKit.Contracts;
using Meshmakers.Octo.ConstructionKit.Analyzers;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Meshmakers.Octo.ConstructionKit.Engine.Tests.SourceGeneration;

/// <summary>
///     AB#6673 guard: OM1005 fails the build when run-time code uses a generated versioned CK element id
///     (<c>FooCkIds.CkThingTypeId</c>) - the tenant may hold a newer model version than the service embeds. The
///     version-less <c>RtCk…</c> constants, the model id, and an immediate <c>.ToRtCkId()</c> are fine.
/// </summary>
public class CkVersionedIdAnalyzerTests
{
    private const string GeneratedIds = """
        using Meshmakers.Octo.ConstructionKit.Contracts;
        namespace Gen;
        public static class FooCkIds
        {
            public static readonly CkModelId CkModelId = new CkModelId("Foo", "2.5.0");
            public static readonly RtCkId<CkTypeId> RtCkThingTypeId = new RtCkId<CkTypeId>("Foo", "Thing-1");
            public static readonly CkId<CkTypeId> CkThingTypeId = new CkId<CkTypeId>(CkModelId, "Thing-1");
            public static readonly CkId<CkAssociationRoleId> CkOwnsRoleId = new CkId<CkAssociationRoleId>(CkModelId, "Owns-1");
        }
        """;

    private static async Task<ImmutableArray<Diagnostic>> AnalyzeAsync(string consumer, string assemblyName = "MyService",
        string? generatedConsumer = null)
    {
        var references = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!)
            .Split(Path.PathSeparator)
            .Select(p => MetadataReference.CreateFromFile(p))
            .Append(MetadataReference.CreateFromFile(typeof(CkId<>).Assembly.Location));
        var trees = new List<SyntaxTree> { CSharpSyntaxTree.ParseText(GeneratedIds), CSharpSyntaxTree.ParseText(consumer) };
        if (generatedConsumer != null)
        {
            trees.Add(CSharpSyntaxTree.ParseText(generatedConsumer));
        }

        var compilation = CSharpCompilation.Create(assemblyName, trees, references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        Assert.DoesNotContain(compilation.GetDiagnostics(), d => d.Severity == DiagnosticSeverity.Error);
        var withAnalyzers = compilation.WithAnalyzers([new CkVersionedIdAnalyzer()]);
        return (await withAnalyzers.GetAnalyzerDiagnosticsAsync()).Where(d => d.Id == "OM1005").ToImmutableArray();
    }

    private static string Consumer(string body) => $$"""
        using Meshmakers.Octo.ConstructionKit.Contracts;
        using Gen;
        public class RuntimeCode
        {
            public object M() { {{body}} }
        }
        """;

    [Fact]
    public async Task VersionedTypeId_IsReported_WithTheVersionlessReplacement()
    {
        var diagnostics = await AnalyzeAsync(Consumer("return FooCkIds.CkThingTypeId;"));

        var diagnostic = Assert.Single(diagnostics);
        Assert.Equal(DiagnosticSeverity.Error, diagnostic.Severity);
        Assert.Contains("FooCkIds.CkThingTypeId", diagnostic.GetMessage());
        Assert.Contains("FooCkIds.RtCkThingTypeId", diagnostic.GetMessage());
    }

    [Fact]
    public async Task VersionedRoleId_IsReported_EveryOccurrence()
    {
        var diagnostics = await AnalyzeAsync(Consumer("var a = FooCkIds.CkOwnsRoleId; return (a, FooCkIds.CkThingTypeId);"));

        Assert.Equal(2, diagnostics.Length);
    }

    [Fact]
    public async Task VersionlessIdsTheModelIdAndAnImmediateToRtCkId_AreAllowed()
    {
        var diagnostics = await AnalyzeAsync(Consumer(
            "var model = FooCkIds.CkModelId; var rt = FooCkIds.RtCkThingTypeId; var converted = FooCkIds.CkThingTypeId.ToRtCkId(); return (model, rt, converted);"));

        Assert.Empty(diagnostics);
    }

    [Fact]
    public async Task TestProjects_AreNotAnalysed()
    {
        var diagnostics = await AnalyzeAsync(Consumer("return FooCkIds.CkThingTypeId;"), "MyService.IntegrationTests");

        Assert.Empty(diagnostics);
    }

    [Fact]
    public async Task GeneratedCode_IsNotAnalysed()
    {
        var generated = """
            // <auto-generated />
            using Gen;
            public class GeneratedUse { public object M() { return FooCkIds.CkThingTypeId; } }
            """;

        var diagnostics = await AnalyzeAsync(Consumer("return 1;"), generatedConsumer: generated);

        Assert.Empty(diagnostics);
    }
}
